// Writes lib/src/theme/tokens.g.dart from the shared design tokens in
// docs/design-system/tokens.json.
//
// Run from apps/mobile:  dart run tool/generate_tokens.dart
// Check only:            dart run tool/generate_tokens.dart --check
import 'dart:convert';
import 'dart:io';

const _source = '../../docs/design-system/tokens.json';
const _target = 'lib/src/theme/tokens.g.dart';

void main(List<String> args) {
  final tokens = jsonDecode(File(_source).readAsStringSync()) as Map<String, dynamic>;
  final output = formatted(generate(tokens));
  final file = File(_target);
  if (args.contains('--check')) {
    if (!file.existsSync() || file.readAsStringSync() != output) {
      stderr.writeln('$_target is out of date. Run: dart run tool/generate_tokens.dart');
      exit(1);
    }
    stdout.writeln('$_target matches the design tokens.');
    return;
  }
  file.writeAsStringSync(output);
  stdout.writeln('Wrote $_target');
}

/// Runs `dart format` on [source], so the check matches the formatted file.
String formatted(String source) {
  final dir = Directory.systemTemp.createTempSync('tokens');
  try {
    final file = File('${dir.path}/tokens.g.dart')..writeAsStringSync(source);
    final result = Process.runSync('dart', ['format', '--page-width', '120', file.path]);
    if (result.exitCode != 0) throw StateError('dart format failed: ${result.stderr}');
    return file.readAsStringSync();
  } finally {
    dir.deleteSync(recursive: true);
  }
}

/// Turns a token colour such as `#1f5a70` or `rgb(0 0 0 / 35%)` into a Dart
/// `Color` constructor.
String colour(String value) {
  final hex = RegExp(r'^#([0-9a-fA-F]{6})$').firstMatch(value);
  if (hex != null) return 'Color(0xFF${hex.group(1)!.toUpperCase()})';
  final rgb = RegExp(r'^rgb\((\d+) (\d+) (\d+) / (\d+)%\)$').firstMatch(value);
  if (rgb != null) {
    final alpha = (int.parse(rgb.group(4)!) * 255 / 100).round();
    final parts = [alpha, for (var i = 1; i <= 3; i++) int.parse(rgb.group(i)!)];
    return 'Color(0x${parts.map((p) => p.toRadixString(16).padLeft(2, '0')).join().toUpperCase()})';
  }
  throw FormatException('Unsupported colour token', value);
}

// Resolve the interface aliases and map roles into concrete colours for Material and MapLibre.
dynamic _at(Map<String, dynamic> tokens, String path) =>
    path.split('.').fold<dynamic>(tokens, (value, key) => (value as Map)[key]);

dynamic _resolve(Map<String, dynamic> tokens, String path, String theme) {
  if (path.startsWith('primitives.palette.')) {
    return _at(tokens, path.replaceFirst('palette.', 'palette.$theme.'));
  }
  if (path.startsWith('map.')) return _at(tokens, path.replaceFirst('map.', 'map.$theme.'));
  final value = _at(tokens, path);
  if (value is String && (value.startsWith('primitives.') || value.startsWith('semantic.'))) {
    return _resolve(tokens, value, theme);
  }
  if (value == null) throw FormatException('Unknown token', path);
  return value;
}

String generate(Map<String, dynamic> tokens) {
  final semantic = _at(tokens, 'semantic.color') as Map<String, dynamic>;
  final compatibility = _at(tokens, 'compatibility.color') as Map<String, dynamic>;
  final mapRoles = {
    'mapLand': 'map.land',
    'mapForest': 'map.forest',
    'mapAgeOutline': 'map.ageOutline',
    'mapSelection': 'map.selection',
  };
  final roles = {
    ...semantic,
    for (final entry in compatibility.entries)
      if ((entry.value as String).startsWith('map.')) entry.key: entry.value,
    ...mapRoles,
  };
  final ageTokens = _at(tokens, 'map.age') as Map<String, dynamic>;
  final chartTokens = _at(tokens, 'chart.series') as Map<String, dynamic>;
  final out = StringBuffer()
    ..writeln('// Generated by tool/generate_tokens.dart from docs/design-system/tokens.json.')
    ..writeln('// Do not edit by hand. Run `make mobile-tokens` after changing the tokens.')
    ..writeln()
    ..writeln("import 'dart:ui';")
    ..writeln()
    ..writeln('/// One theme\'s interface colours.')
    ..writeln('class FimraPalette {')
    ..writeln('  /// Builds a palette using the original named colours.')
    ..writeln('  const FimraPalette({')
    ..writeAll(
      [...compatibility.keys, 'text', 'textSecondary', 'danger', 'scrim'].map((name) => '    required Color $name,\n'),
    )
    ..writeln('    required List<Color> fireAge,')
    ..writeln('    required List<Color> chart,')
    ..writeln('  }) : this._roles(')
    ..writeAll(
      compatibility.entries.map((entry) {
        final path = entry.value as String;
        final name = path.startsWith('map.') ? entry.key : path.split('.').last;
        return '    $name: ${entry.key},\n';
      }),
    )
    ..writeAll(['text', 'textSecondary', 'danger', 'scrim', 'fireAge', 'chart'].map((name) => '    $name: $name,\n'))
    ..writeln('    surfaceRaised: card,')
    ..writeln('    controlBoundary: textSecondary,')
    ..writeln('    focus: brand,')
    ..writeln('    successText: text,')
    ..writeln('    shadow: const ${colour(_resolve(tokens, 'semantic.color.shadow', 'light') as String)},')
    ..writeln('    mapLand: card,')
    ..writeln('    mapForest: neutralMark,')
    ..writeln('    mapAgeOutline: card,')
    ..writeln('    mapSelection: brand,')
    ..writeln('  );')
    ..writeln()
    ..writeln('  const FimraPalette._roles({')
    ..writeAll(roles.keys.map((n) => '    required this.$n,\n'))
    ..writeln('    required this.fireAge,')
    ..writeln('    required this.chart,')
    ..writeln('  });')
    ..writeAll(roles.keys.map((n) => '  final Color $n;\n'))
    ..writeAll(
      compatibility.entries
          .where((entry) => !roles.containsKey(entry.key))
          .map((entry) => '  Color get ${entry.key} => ${(entry.value as String).split('.').last};\n'),
    )
    ..writeln('  /// Fire-age colours. Index 0 is the most recent detection.')
    ..writeln('  final List<Color> fireAge;')
    ..writeln('  /// Chart colours, used in this fixed order.')
    ..writeln('  final List<Color> chart;')
    ..writeln('}')
    ..writeln();
  for (final name in ['light', 'dark']) {
    final age = ageTokens[name] as List;
    final chart = chartTokens[name] as List;
    out
      ..writeln('const ${name}Palette = FimraPalette._roles(')
      ..writeAll(roles.keys.map((n) => '  $n: ${colour(_resolve(tokens, roles[n] as String, name) as String)},\n'))
      ..writeln('  fireAge: [${age.map((c) => colour(c as String)).join(', ')}],')
      ..writeln('  chart: [${chart.map((c) => colour(c as String)).join(', ')}],')
      ..writeln(');')
      ..writeln();
  }
  final status = _at(tokens, 'components.status') as Map<String, dynamic>;
  out.writeln('/// Reserved for state. Always shown with an icon and a label.');
  out.writeln('abstract final class FimraStatus {');
  for (final key in ['good', 'warning', 'serious', 'critical']) {
    out.writeln('  static const $key = ${colour(_resolve(tokens, status[key] as String, 'light') as String)};');
  }
  out.writeln('}');
  out.writeln();
  final logo = tokens['logo'] as Map<String, dynamic>;
  out.writeln('/// Logo colours only. Never used for interface elements.');
  out.writeln('abstract final class FimraLogoColours {');
  for (final key in logo.keys.where((k) => k != 'comment')) {
    out.writeln('  static const $key = ${colour(logo[key] as String)};');
  }
  out.writeln('}');
  out.writeln();
  final steps = ageTokens['steps'] as List;
  out.writeln('/// Labels for the fire-age steps, in the same order as the colours.');
  out.writeln('const fireAgeSteps = [${steps.map((s) => "'$s'").join(', ')}];');
  out.writeln();
  final type = _at(tokens, 'semantic.type') as Map<String, dynamic>;
  out
    ..writeln('/// One step of the type scale.')
    ..writeln('class FimraTypeStep {')
    ..writeln('  const FimraTypeStep(this.size, this.lineHeight, this.weight, this.trackingEm);')
    ..writeln('  final double size;')
    ..writeln('  final double lineHeight;')
    ..writeln('  final double weight;')
    ..writeln('  final double trackingEm;')
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class FimraType {');
  for (final entry in type.entries) {
    final step = _resolve(tokens, entry.value as String, 'light') as Map;
    out.writeln(
      '  static const ${entry.key} = FimraTypeStep('
      '${step['sizePx']}, ${step['lineHeightPx']}, ${step['weight']}, ${step['trackingEm']});',
    );
  }
  final radius = _at(tokens, 'semantic.radiusPx') as Map<String, dynamic>;
  final touch = _at(tokens, 'density.touchTargetMinPx.mobile');
  out
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class FimraSize {')
    ..writeln('  /// Smallest touch target on the phone app, in logical pixels.')
    ..writeln('  static const double touchTarget = $touch;')
    ..writeln('  static const double spaceUnit = ${_at(tokens, 'primitives.spacePx.base')};')
    ..writeln('  static const spaceSteps = ${_at(tokens, 'primitives.spacePx.steps')};')
    ..writeln('  static const double focusWidth = ${_resolve(tokens, 'semantic.focusPx.width', 'light')};')
    ..writeln('  static const double focusOffset = ${_resolve(tokens, 'semantic.focusPx.offset', 'light')};');
  for (final entry in radius.entries) {
    final name = entry.key[0].toUpperCase() + entry.key.substring(1);
    out.writeln('  static const double radius$name = ${_resolve(tokens, entry.value as String, 'light')};');
  }
  out
    ..writeln('}')
    ..writeln()
    ..writeln('/// The visual density is independent of brightness.')
    ..writeln('enum FimraDensity {');
  for (final (name, separator) in [('comfortable', ','), ('compact', ';')]) {
    final density = _at(tokens, 'density.$name') as Map;
    out.writeln('  $name(${density['controlPx']}, ${density['rowPx']})$separator');
  }
  out
    ..writeln('  const FimraDensity(this.controlHeight, this.rowHeight);')
    ..writeln('  final double controlHeight;')
    ..writeln('  final double rowHeight;')
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class FimraElevation {')
    ..writeln('  static const double menu = ${_resolve(tokens, 'semantic.elevation.menuDp', 'light')};')
    ..writeln('  static const double dialog = ${_resolve(tokens, 'semantic.elevation.dialogDp', 'light')};')
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class FimraMotion {');
  final motion = _at(tokens, 'semantic.motionMs') as Map<String, dynamic>;
  for (final entry in motion.entries) {
    final ms = _resolve(tokens, entry.value as String, 'light');
    out.writeln('  static const ${entry.key} = Duration(milliseconds: $ms);');
  }
  out
    ..writeln('}')
    ..writeln()
    ..writeln('const mapForestOpacity = ${_at(tokens, 'map.forestOpacity')};');
  return out.toString();
}

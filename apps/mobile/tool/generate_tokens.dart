// Writes lib/src/theme/tokens.g.dart from the shared design tokens in
// docs/design-system/tokens.json.
//
// Run from apps/mobile:  dart run tool/generate_tokens.dart
// Check only:            dart run tool/generate_tokens.dart --check
import 'dart:convert';
import 'dart:io';

const _source = '../../docs/design-system/tokens.json';
const _target = 'lib/src/theme/tokens.g.dart';

void main(List<String> args) {
  final tokens = jsonDecode(File(_source).readAsStringSync()) as Map<String, dynamic>;
  final output = formatted(generate(tokens));
  final file = File(_target);
  if (args.contains('--check')) {
    if (!file.existsSync() || file.readAsStringSync() != output) {
      stderr.writeln('$_target is out of date. Run: dart run tool/generate_tokens.dart');
      exit(1);
    }
    stdout.writeln('$_target matches the design tokens.');
    return;
  }
  file.writeAsStringSync(output);
  stdout.writeln('Wrote $_target');
}

/// Runs `dart format` on [source], so the check matches the formatted file.
String formatted(String source) {
  final dir = Directory.systemTemp.createTempSync('tokens');
  try {
    final file = File('${dir.path}/tokens.g.dart')..writeAsStringSync(source);
    final result = Process.runSync('dart', ['format', '--page-width', '120', file.path]);
    if (result.exitCode != 0) throw StateError('dart format failed: ${result.stderr}');
    return file.readAsStringSync();
  } finally {
    dir.deleteSync(recursive: true);
  }
}

/// Turns a token colour such as `#1f5a70` or `rgb(0 0 0 / 35%)` into a Dart
/// `Color` constructor.
String colour(String value) {
  final hex = RegExp(r'^#([0-9a-fA-F]{6})$').firstMatch(value);
  if (hex != null) return 'Color(0xFF${hex.group(1)!.toUpperCase()})';
  final rgb = RegExp(r'^rgb\((\d+) (\d+) (\d+) / (\d+)%\)$').firstMatch(value);
  if (rgb != null) {
    final alpha = (int.parse(rgb.group(4)!) * 255 / 100).round();
    final parts = [alpha, for (var i = 1; i <= 3; i++) int.parse(rgb.group(i)!)];
    return 'Color(0x${parts.map((p) => p.toRadixString(16).padLeft(2, '0')).join().toUpperCase()})';
  }
  throw FormatException('Unsupported colour token', value);
}

String generate(Map<String, dynamic> tokens) {
  final colours = tokens['color'] as Map<String, dynamic>;
  final light = colours['light'] as Map<String, dynamic>;
  final dark = colours['dark'] as Map<String, dynamic>;
  final names = light.keys.toList();
  if (dark.keys.toSet().difference(names.toSet()).isNotEmpty || dark.length != light.length) {
    throw const FormatException('Light and dark themes must define the same colours');
  }
  final out = StringBuffer()
    ..writeln('// Generated by tool/generate_tokens.dart from docs/design-system/tokens.json.')
    ..writeln('// Do not edit by hand. Run `make mobile-tokens` after changing the tokens.')
    ..writeln()
    ..writeln("import 'dart:ui';")
    ..writeln()
    ..writeln('/// One theme\'s interface colours.')
    ..writeln('class FimraPalette {')
    ..writeln('  const FimraPalette({')
    ..writeAll(names.map((n) => '    required this.$n,\n'))
    ..writeln('    required this.fireAge,')
    ..writeln('    required this.chart,')
    ..writeln('  });')
    ..writeAll(names.map((n) => '  final Color $n;\n'))
    ..writeln('  /// Fire-age colours. Index 0 is the most recent detection.')
    ..writeln('  final List<Color> fireAge;')
    ..writeln('  /// Chart colours, used in this fixed order.')
    ..writeln('  final List<Color> chart;')
    ..writeln('}')
    ..writeln();
  for (final (name, theme) in [('light', light), ('dark', dark)]) {
    final age = (colours['fireAge'] as Map<String, dynamic>)[name] as List;
    final chart = (colours['chart'] as Map<String, dynamic>)[name] as List;
    out
      ..writeln('const ${name}Palette = FimraPalette(')
      ..writeAll(names.map((n) => '  $n: ${colour(theme[n] as String)},\n'))
      ..writeln('  fireAge: [${age.map((c) => colour(c as String)).join(', ')}],')
      ..writeln('  chart: [${chart.map((c) => colour(c as String)).join(', ')}],')
      ..writeln(');')
      ..writeln();
  }
  final status = colours['status'] as Map<String, dynamic>;
  out.writeln('/// Reserved for state. Always shown with an icon and a label.');
  out.writeln('abstract final class FimraStatus {');
  for (final key in ['good', 'warning', 'serious', 'critical']) {
    out.writeln('  static const $key = ${colour(status[key] as String)};');
  }
  out.writeln('}');
  out.writeln();
  final logo = colours['logo'] as Map<String, dynamic>;
  out.writeln('/// Logo colours only. Never used for interface elements.');
  out.writeln('abstract final class FimraLogoColours {');
  for (final key in logo.keys.where((k) => k != 'comment')) {
    out.writeln('  static const $key = ${colour(logo[key] as String)};');
  }
  out.writeln('}');
  out.writeln();
  final steps = (colours['fireAge'] as Map<String, dynamic>)['steps'] as List;
  out.writeln('/// Labels for the fire-age steps, in the same order as the colours.');
  out.writeln('const fireAgeSteps = [${steps.map((s) => "'$s'").join(', ')}];');
  out.writeln();
  final font = tokens['font'] as Map<String, dynamic>;
  final size = font['sizePx'] as Map<String, dynamic>;
  final line = font['lineHeightPx'] as Map<String, dynamic>;
  final weight = font['weight'] as Map<String, dynamic>;
  final tracking = font['trackingEm'] as Map<String, dynamic>;
  out
    ..writeln('/// One step of the type scale.')
    ..writeln('class FimraTypeStep {')
    ..writeln('  const FimraTypeStep(this.size, this.lineHeight, this.weight, this.trackingEm);')
    ..writeln('  final double size;')
    ..writeln('  final double lineHeight;')
    ..writeln('  final double weight;')
    ..writeln('  final double trackingEm;')
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class FimraType {');
  for (final key in size.keys) {
    out.writeln('  static const $key = FimraTypeStep(${size[key]}, ${line[key]}, ${weight[key]}, ${tracking[key]});');
  }
  final radius = tokens['radiusPx'] as Map<String, dynamic>;
  out
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class FimraSize {')
    ..writeln('  /// Smallest touch target on the phone app, in logical pixels.')
    ..writeln('  static const double touchTarget = ${(tokens['touchTargetMinPx'] as Map)['mobile']};')
    ..writeln('  static const double spaceUnit = ${(tokens['space'] as Map)['unitPx']};')
    ..writeln('  static const double radiusControl = ${radius['control']};')
    ..writeln('  static const double radiusCard = ${radius['card']};')
    ..writeln('  static const double radiusPill = ${radius['pill']};')
    ..writeln('}');
  return out.toString();
}
